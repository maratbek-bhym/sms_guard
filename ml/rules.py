SUPPORTED_LANGS = ("ru", "kk", "en")


def find_groups(text: str) -> dict:
    """Возвращает {группа: [сработавшие выражения]} по нормализованному тексту (все языки сразу)."""
    t = normalize_sms(text)
    found = {}
    for g, spec in RULES.items():
        hits = [p for lang in SUPPORTED_LANGS for p in spec[lang] if p in t]
        if hits:
            found[g] = hits
    return found


def has_code_warning(text: str) -> bool:
    t = normalize_sms(text)
    return any(p in t for lang in SUPPORTED_LANGS for p in CODE_WARNING[lang])


def group_title(g: str) -> str:
    return RULES.get(g, {}).get("title", g)
